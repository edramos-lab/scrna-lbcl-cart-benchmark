def compute_tsne_2d(X, perplexity=30.0, seed=42, prefer_gpu=True):
    """Return (2D embedding as np.ndarray, backend label).

    Reduces to 50 PCA components first (for speed), then runs 2D t-SNE.
    Tries RAPIDS/cuML on GPU when prefer_gpu is True; otherwise / on any
    failure falls back to sklearn on CPU.
    """
    n_pca = int(min(50, X.shape[1]))
    if prefer_gpu:
        try:
            import cupy as cp
            from cuml.decomposition import PCA as cuPCA
            from cuml.manifold import TSNE as cuTSNE
            print("🔮 Computing 2D t-SNE on GPU (cuML: PCA-50 → t-SNE)...")
            X_gpu = cp.asarray(X)
            X_pca = cuPCA(n_components=n_pca).fit_transform(X_gpu)
            emb = cuTSNE(n_components=2, perplexity=perplexity, random_state=seed).fit_transform(X_pca)
            emb = emb.get() if hasattr(emb, "get") else np.asarray(emb)
            return np.asarray(emb), "GPU (cuML)"
        except Exception as e:
            print(f"⚠️  GPU t-SNE unavailable ({e}); falling back to CPU sklearn t-SNE.")
    from sklearn.decomposition import PCA as skPCA
    print("🖥️  Computing 2D t-SNE on CPU (sklearn: PCA-50 → t-SNE)...")
    X_pca = skPCA(n_components=n_pca, random_state=seed).fit_transform(X)
    emb = TSNE(n_components=2, perplexity=perplexity, random_state=seed).fit_transform(X_pca)
    return np.asarray(emb), "CPU (sklearn)"


# ============================================================
#  3D UMAP — GPU-accelerated (RAPIDS/cuML) with CPU fallback
# ============================================================
def compute_umap_3d(X, n_neighbors=15, min_dist=0.1, seed=42, prefer_gpu=True):
    """Return (3D embedding as np.ndarray, backend label).

    Tries RAPIDS/cuML's UMAP on GPU when prefer_gpu is True; falls back to the
    CPU umap-learn package if cuML is unavailable; returns (None, "unavailable")
    if neither package is installed, so the caller can skip gracefully.
    """
    if prefer_gpu:
        try:
            import cupy as cp
            from cuml.manifold import UMAP as cuUMAP
            print(f"🔮 Computing 3D UMAP on GPU (cuML: n_neighbors={n_neighbors}, min_dist={min_dist})...")
            X_gpu = cp.asarray(X)
            emb = cuUMAP(n_components=3, n_neighbors=n_neighbors, min_dist=min_dist,
                        random_state=seed).fit_transform(X_gpu)
            emb = emb.get() if hasattr(emb, "get") else np.asarray(emb)
            return np.asarray(emb), "GPU (cuML)"
        except Exception as e:
            print(f"⚠️  GPU UMAP unavailable ({e}); trying CPU umap-learn.")
    try:
        from umap import UMAP as skUMAP
        print(f"🖥️  Computing 3D UMAP on CPU (umap-learn: n_neighbors={n_neighbors}, min_dist={min_dist})...")
        emb = skUMAP(n_components=3, n_neighbors=n_neighbors, min_dist=min_dist,
                     random_state=seed).fit_transform(X)
        return np.asarray(emb), "CPU (umap-learn)"
    except Exception as e:
        print(f"⚠️  UMAP unavailable on GPU or CPU ({e}); skipping the 3D UMAP CSV export. "
              f"Install 'umap-learn' (CPU) or RAPIDS cuML (GPU) to enable it.")
        return None, "unavailable"


def save_combined_tsne_plot(embeddings, cell_types, tumor_status, out_dir, backend=""):
    """Static 'combined' 2D t-SNE: color = cell lineage, marker = tumor response.
    Returns [pdf_path, png_path] for downloading."""
    cell_types = np.asarray(cell_types)
    tumor_status = np.asarray(tumor_status)
    ctypes = sorted(pd.unique(cell_types).tolist())
    tstatuses = sorted(pd.unique(tumor_status).tolist())
    palette = plt.get_cmap("tab10")
    markers = ['o', '^', 's', 'D', 'v', 'P', 'X', '*']
    color_map = {ct: palette(i % 10) for i, ct in enumerate(ctypes)}
    marker_map = {ts: markers[i % len(markers)] for i, ts in enumerate(tstatuses)}

    fig, ax = plt.subplots(figsize=(9, 7), dpi=300)
    for ct in ctypes:
        for ts in tstatuses:
            mask = (cell_types == ct) & (tumor_status == ts)
            if mask.sum() == 0:
                continue
            ax.scatter(embeddings[mask, 0], embeddings[mask, 1], s=6, alpha=0.6,
                       color=color_map[ct], marker=marker_map[ts],
                       edgecolors='none', label=f"{ct} · {ts}")
    ax.set_title(f"Combined 2D t-SNE — Cell Lineage × Tumor Response [{backend}]",
                 fontweight='bold', pad=10)
    ax.set_xlabel("t-SNE 1", fontweight='bold')
    ax.set_ylabel("t-SNE 2", fontweight='bold')
    ax.legend(loc='best', fontsize=7, markerscale=2, ncol=2, framealpha=0.9)
    ax.grid(True, linestyle='--', alpha=0.3)
    fig.tight_layout()
    pdf = os.path.join(out_dir, "tsne_2d_combined.pdf")
    png = os.path.join(out_dir, "tsne_2d_combined.png")
    fig.savefig(pdf, bbox_inches='tight', dpi=300)
    fig.savefig(png, bbox_inches='tight', dpi=300)
    plt.close(fig)
    return [pdf, png]


