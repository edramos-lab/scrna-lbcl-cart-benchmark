import threading
from contextlib import nullcontext


class GPUPowerMonitor:
    """Background sampler of real GPU power draw (watts) via NVML.

    Use as a context manager around a training loop; call mark() at epoch
    boundaries. Falls back gracefully (available=False) with no GPU/NVML.
    """
    def __init__(self, sample_ms=200, device_index=0):
        self.sample_ms = max(int(sample_ms), 20)
        self.device_index = device_index
        self.times, self.watts, self.marks = [], [], []
        self._stop = threading.Event()
        self._thread = None
        self._t0 = None
        try:
            import pynvml
            pynvml.nvmlInit()
            self._nvml = pynvml
            self._handle = pynvml.nvmlDeviceGetHandleByIndex(device_index)
        except Exception as e:
            print(f"⚠️  NVML power monitoring unavailable ({e}); "
                  f"install 'nvidia-ml-py' and use a GPU runtime. Skipping power trace for this model.")
            self._nvml = None
            self._handle = None

    @property
    def available(self):
        return self._nvml is not None

    def _loop(self):
        while not self._stop.is_set():
            try:
                mw = self._nvml.nvmlDeviceGetPowerUsage(self._handle)  # milliwatts
                self.times.append(time.time() - self._t0)
                self.watts.append(mw / 1000.0)
            except Exception:
                pass
            self._stop.wait(self.sample_ms / 1000.0)

    def mark(self):
        """Record an epoch-boundary timestamp (relative to monitor start)."""
        if self.available and self._t0 is not None:
            self.marks.append(time.time() - self._t0)

    def __enter__(self):
        if self.available:
            self._t0 = time.time()
            self._stop.clear()
            self._thread = threading.Thread(target=self._loop, daemon=True)
            self._thread.start()
        return self

    def __exit__(self, *exc):
        if self.available and self._thread is not None:
            self._stop.set()
            self._thread.join(timeout=2.0)
        return False

    def energy_joules(self):
        """Integrate power over time (trapezoidal) for a MEASURED energy figure."""
        if len(self.times) >= 2:
            _trapz = getattr(np, "trapezoid", np.trapz)  # numpy>=2 renamed trapz -> trapezoid
            return float(_trapz(self.watts, self.times))
        return None


def save_power_plot(monitor, name, out_dir):
    """Write a per-model 'power vs. time during training' figure and return its path."""
    if not monitor.available or len(monitor.times) < 2:
        return None
    avg_w = float(np.mean(monitor.watts))
    peak_w = float(np.max(monitor.watts))
    fig, ax = plt.subplots(figsize=(9, 4), dpi=300)
    ax.plot(monitor.times, monitor.watts, color='tab:red', linewidth=1.5, label='GPU power')
    ax.fill_between(monitor.times, monitor.watts, alpha=0.15, color='tab:red')
    for m in monitor.marks:                       # dotted lines at epoch boundaries
        ax.axvline(m, color='grey', linestyle=':', linewidth=0.8, alpha=0.6)
    ax.axhline(avg_w, color='navy', linestyle='--', linewidth=1.0, label=f'Mean {avg_w:.1f} W')
    ax.set_title(f"GPU Power Usage During Training — {name}\n"
                 f"(mean {avg_w:.1f} W, peak {peak_w:.1f} W)", fontweight='bold', pad=10)
    ax.set_xlabel("Training time (s)", fontweight='bold')
    ax.set_ylabel("Power draw (W)", fontweight='bold')
    ax.legend(loc='upper right')
    ax.grid(True, linestyle='--', alpha=0.3)
    fig.tight_layout()
    safe = name.replace(' ', '_').replace('(', '').replace(')', '').replace('/', '-')
    path = os.path.join(out_dir, f"power_training_{safe}.png")
    fig.savefig(path, dpi=300, bbox_inches='tight')
    plt.close(fig)
    return path


