class MultiTaskNet(nn.Module):
    # Defaults reproduce the original architecture; Optuna can override hidden_dim/dropout.
    def __init__(self, input_dim, hidden_dim=256, dropout=0.3):
        super().__init__()
        self.backbone = nn.Sequential(nn.Linear(input_dim, hidden_dim), nn.ReLU(), nn.Dropout(dropout))
        self.type_head = nn.Linear(hidden_dim, 3)
        self.status_head = nn.Linear(hidden_dim, 2)
    def forward(self, x):
        feat = self.backbone(x)
        return self.type_head(feat), self.status_head(feat)

# ==========================================
# SOTA MODEL 1: ARQUITECTURA TIPO scBERT (Transformer)
# ==========================================
class scBERT_Inspired(nn.Module):
    # d_model kept fixed at 256; nhead must divide d_model, so tune nhead in {2,4,8}.
    def __init__(self, input_dim, d_model=256, nhead=4, num_layers=2, dim_feedforward=512, dropout=0.1):
        super().__init__()
        assert d_model % nhead == 0, "nhead must divide d_model"
        # Simula capas de atención multi-cabeza aplicadas a tokens de expresión génica
        self.gene_encoder = nn.Linear(input_dim, d_model)
        encoder_layer = nn.TransformerEncoderLayer(
            d_model=d_model, nhead=nhead, dim_feedforward=dim_feedforward,
            dropout=dropout, batch_first=True)
        self.transformer = nn.TransformerEncoder(encoder_layer, num_layers=num_layers)
        self.type_head = nn.Linear(d_model, 3)
        self.status_head = nn.Linear(d_model, 2)
    def forward(self, x):
        x = self.gene_encoder(x).unsqueeze(1) # Inyectar dimensión temporal simulada para el Transformer
        x = self.transformer(x).squeeze(1)
        return self.type_head(x), self.status_head(x)

# ==========================================
# SOTA MODEL 2: ARQUITECTURA TIPO scGPT (Generative Bottleneck)
# ==========================================
class scGPT_Inspired(nn.Module):
    def __init__(self, input_dim, hidden_dim=512, bottleneck_dim=128, dropout=0.0):
        super().__init__()
        # Basado en un cuello de botella denso que condensa la variabilidad latente de las células
        self.embedding = nn.Sequential(
            nn.Linear(input_dim, hidden_dim), nn.GELU(),
            nn.Dropout(dropout), nn.Linear(hidden_dim, bottleneck_dim))
        self.type_head = nn.Linear(bottleneck_dim, 3)
        self.status_head = nn.Linear(bottleneck_dim, 2)
    def forward(self, x):
        feat = self.embedding(x)
        return self.type_head(feat), self.status_head(feat)

# ==========================================
# SOTA MODEL 3: ARQUITECTURA TIPO Geneformer (Deep GRN)
# ==========================================
class Geneformer_Inspired(nn.Module):
    def __init__(self, input_dim, hidden_dim=256, dropout=0.0):
        super().__init__()
        # Red profunda con conexiones residuales explícitas para capturar redes de regulación genética (GRN)
        self.layer1 = nn.Sequential(nn.Linear(input_dim, hidden_dim), nn.LayerNorm(hidden_dim), nn.ReLU(), nn.Dropout(dropout))
        self.layer2 = nn.Sequential(nn.Linear(hidden_dim, hidden_dim), nn.LayerNorm(hidden_dim), nn.ReLU(), nn.Dropout(dropout))
        self.type_head = nn.Linear(hidden_dim, 3)
        self.status_head = nn.Linear(hidden_dim, 2)
    def forward(self, x):
        x1 = self.layer1(x)
        x2 = self.layer2(x1) + x1 # Conexión residual nativa
        return self.type_head(x2), self.status_head(x2)

